import { expect, test } from "@playwright/test";

test("records an explicitly confirmed result separately from browser key detection", async ({ page }) => {
  await page.goto("/#/device-verification");
  await expect(page.getByRole("heading", { name: "標準問題の実機検証" })).toBeVisible();
  await expect(page.getByText("全 180 問 / 確認済み（正常動作）0 問")).toBeVisible();
  await page.getByRole("combobox", { name: "カテゴリ" }).selectOption("windows");
  await page.getByRole("combobox", { name: "難易度" }).selectOption("beginner");
  await page.getByRole("combobox", { name: "実機検証状況" }).selectOption("unverified");
  const item = page.getByRole("listitem").filter({ hasText: "windows-copy" });
  await expect(item).toContainText("未確認");
  await item.getByRole("button", { name: "検証する" }).click();
  await page.getByRole("region", { name: "ショートカット回答欄" }).focus();
  await page.keyboard.press("Control+C");
  await expect(page.getByText("ブラウザーで一致を検出しました。対象アプリの動作は未判定です。")).toBeVisible();
  await expect(page.getByText("全 180 問 / 確認済み（正常動作）0 問")).toBeVisible();
  await page.getByLabel("OS・バージョン").fill("Windows 11 test");
  await page.getByLabel("ブラウザー・バージョン").fill("Chromium test");
  await page.getByLabel("対象アプリ・バージョン").fill("テスト用アプリ");
  await page.getByLabel("キーボード配列").fill("JIS test");
  await page.getByRole("combobox", { name: "対象アプリでの実機検証結果" }).selectOption("success");
  await page.getByLabel("対象アプリを実機で操作し、期待した動作を確認しました。").check();
  await page.getByRole("button", { name: "検証結果を登録" }).click();
  await expect(page.getByText("実機検証記録を保存しました。学習履歴は変更していません。")).toBeVisible();
  await expect(page.getByText("全 180 問 / 確認済み（正常動作）1 問")).toBeVisible();
  await page.reload();
  await expect(page.getByText("全 180 問 / 確認済み（正常動作）1 問")).toBeVisible();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "検証結果をJSON出力" }).click();
  expect((await downloadPromise).suggestedFilename()).toBe("shortcut-trainer-device-verifications.json");
  await page.getByRole("button", { name: "次の未確認問題へ" }).click();
  await expect(page.getByRole("heading", { name: /検証する:/ })).toBeVisible();
  await page.goto("/#/questions");
  const backupPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "バックアップを保存" }).click();
  const backup = await backupPromise;
  await page.getByLabel("復元ファイル").setInputFiles(await backup.path());
  await expect(page.getByText(/実機検証 1 件/)).toBeVisible();
  page.once("dialog", (dialog) => dialog.accept());
  await page.getByRole("button", { name: "復元を実行" }).click();
  await expect(page.getByRole("status")).toContainText("既存を保持");
});
